#!/usr/bin/env bash
# Packages the two unified 32-bit ARM (armv7l) webOS IPKs with native libass 0.17.4
# enabled out of the box:
#   1. dist/com.edde746.plezy_<ver>_arm_webos25-26.ipk (factory webOS 25/26, glibc 2.38, wl_webos_shell v2)
#   2. dist/com.edde746.plezy_<ver>_arm_webos6-24.ipk  (compat-patched webOS 22-24 / Re:New, glibc 2.35, wl_webos_shell v1)
#
# Usage:
#   ./scripts/webos/build_32bit_ipk.sh [--target all|webos25-26|webos6-24] [--version <x.y.z>] [--side-by-side] [--orig-ipk <path>]
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
WORK_DIR="${WORK_DIR:-$(cd "$REPO_ROOT/.." && pwd)}"
WEBOS_SDK_DIR="${WEBOS_SDK_DIR:-/usr/local/starfish-sdk-x86_64}"
OUT_DIR="${OUT_DIR:-$REPO_ROOT/dist}"

if [ -f "$REPO_ROOT/scripts/webos/env.sh" ]; then
  source "$REPO_ROOT/scripts/webos/env.sh"
fi

TARGET_MODE="all"
SIDE_BY_SIDE=0
ORIG_IPK_ARG="${ORIG_IPK:-}"
PKG_VERSION_ARG="${WEBOS_PKG_VERSION:-}"

while [ $# -gt 0 ]; do
  case "$1" in
    --target)
      if [ $# -lt 2 ]; then
        echo "ERROR: --target requires an argument (all, webos25-26, or webos6-24)" >&2
        exit 2
      fi
      TARGET_MODE="$2"
      shift 2
      ;;
    --target=*)
      TARGET_MODE="${1#*=}"
      shift
      ;;
    --version)
      if [ $# -lt 2 ]; then
        echo "ERROR: --version requires a 3-part SemVer argument (MAJOR.MINOR.PATCH)" >&2
        exit 2
      fi
      PKG_VERSION_ARG="$2"
      shift 2
      ;;
    --version=*)
      PKG_VERSION_ARG="${1#*=}"
      shift
      ;;
    --side-by-side)
      SIDE_BY_SIDE=1
      shift
      ;;
    --orig-ipk)
      if [ $# -lt 2 ]; then
        echo "ERROR: --orig-ipk requires a path argument" >&2
        exit 2
      fi
      ORIG_IPK_ARG="$2"
      shift 2
      ;;
    --orig-ipk=*)
      ORIG_IPK_ARG="${1#*=}"
      shift
      ;;
    -h|--help)
      echo "Usage: $0 [--target all|webos25-26|webos6-24] [--version <x.y.z>] [--side-by-side] [--orig-ipk <path>]"
      exit 0
      ;;
    *)
      echo "ERROR: Unknown option: $1" >&2
      echo "Usage: $0 [--target all|webos25-26|webos6-24] [--version <x.y.z>] [--side-by-side] [--orig-ipk <path>]" >&2
      exit 2
      ;;
  esac
done

