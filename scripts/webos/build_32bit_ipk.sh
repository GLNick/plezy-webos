# Prepends libwebos_compat32.so at DT_NEEDED[0] along with RPATH (and optional
# interpreter) in a SINGLE patchelf invocation (~3.5 KB overhead instead of the
# 5.2 MB bloat caused by repeated remove-needed/add-needed passes).
# libwebos_compat32.so itself declares DT_NEEDED on libdl.so.2 so dlopen/dlsym
# are always loaded even for libraries that did not originally link libdl.
prepend_compat_lib_single_pass() {
  local target="$1"
  local rpath_val="$2"
  local interp_val="${3:-}"
  local existing lib has_compat=0

  existing="$(patchelf --print-needed "$target" 2>/dev/null || true)"
  for lib in $existing; do
    if [ "$lib" = "libwebos_compat32.so" ]; then
      has_compat=1
    fi
  done

  local args=()
  if [ -n "$interp_val" ]; then
    args+=(--set-interpreter "$interp_val")
  fi
  args+=(--set-rpath "$rpath_val" --force-rpath)
  if [ "$has_compat" -eq 1 ]; then
    args+=(--remove-needed libwebos_compat32.so)
  fi
  args+=(--add-needed libwebos_compat32.so)

  patchelf "${args[@]}" "$target"
}

strip_unreachable_desktop_assets() {
  local app_dir="$1"
  local assets_dir="$app_dir/data/flutter_assets/assets"
  # Desktop/mobile mpv GLSL upscalers (~3.2 MB) and iOS SpatialAudioBridge license
  # are never loaded on webOS (PlayerWebos uses NDL hardware video output).
  rm -rf \
    "$assets_dir/shaders/artcnn" \
    "$assets_dir/shaders/anime4k" \
    "$assets_dir/shaders/nvscaler"
  rm -f "$assets_dir/licenses/SpatialAudioBridge.txt"
}

