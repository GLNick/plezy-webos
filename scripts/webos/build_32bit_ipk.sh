if [ -z "$ORIG_IPK" ] || [ ! -f "$ORIG_IPK" ]; then
  ORIG_IPK="$(find "$REPO_ROOT/build" -path "$LIBASS_WORK" -prune -o -name "*.ipk" -print 2>/dev/null | grep -v -E "(-32bit|_webos6-24|_webos25-26|_libass)\.ipk" | head -n 1 || true)"
